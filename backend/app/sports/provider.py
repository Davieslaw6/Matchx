"""Provider contract with explicit capability-aware unsupported results."""
from dataclasses import dataclass
from datetime import date
from typing import Any, Protocol

@dataclass(frozen=True)
class CapabilityFlags:
    supports_odds: bool = False
    supports_xg: bool = False
    supports_injuries: bool = False
    supports_cards: bool = False
    supports_corners: bool = False

@dataclass(frozen=True)
class Unsupported:
    capability: str
    reason: str

class SportsDataProvider(Protocol):
    name: str
    capabilities: CapabilityFlags
    async def competitions(self) -> list[dict[str, Any]]: ...
    async def teams(self, competition_id: str) -> list[dict[str, Any]]: ...
    async def fixtures(self, start: date, end: date, competition_id: str | None = None) -> list[dict[str, Any]]: ...
    async def results(self, start: date, end: date, competition_id: str | None = None) -> list[dict[str, Any]]: ...
    async def standings(self, competition_id: str) -> list[dict[str, Any]]: ...
    async def match_statistics(self, fixture_id: str) -> dict[str, Any] | Unsupported: ...
    async def head_to_head(self, home_team_id: str, away_team_id: str) -> list[dict[str, Any]]: ...
    async def odds(self, fixture_id: str) -> list[dict[str, Any]] | Unsupported: ...
    async def injuries(self, fixture_id: str) -> list[dict[str, Any]] | Unsupported: ...
    async def team_news(self, team_id: str) -> list[dict[str, Any]] | Unsupported: ...
